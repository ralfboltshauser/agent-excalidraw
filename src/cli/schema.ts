import { z } from "zod";
import { commands } from "../shared/commands.js";
import { AppError, type Request } from "../shared/types.js";
export const commonShape = {
  document: z
    .string()
    .optional()
    .describe(
      "Document ID from new/open/snapshot; mutations never target focus implicitly",
    ),
  epoch: z.string().optional().describe("Runtime document epoch from snapshot"),
  expectedRevision: z
    .number()
    .int()
    .nonnegative()
    .optional()
    .describe("Content revision from the latest inspected snapshot"),
  requestId: z
    .string()
    .optional()
    .describe(
      "Unique operation ID; reuse only to reconcile the same operation",
    ),
  session: z
    .string()
    .optional()
    .describe("Stable agent-session name, used for Stop/Resume"),
};
const coordinate = z.number().min(-1e7).max(1e7);
const fontFamily = z
  .union([
    z.literal(1),
    z.literal(2),
    z.literal(3),
    z.literal(5),
    z.literal(6),
    z.literal(7),
    z.literal(8),
    z.literal(9),
  ])
  .describe(
    "Bundled font ID: 1 Virgil, 2 Helvetica, 3 Cascadia, 5 Excalifont, 6 Nunito, 7 Lilita One, 8 Comic Shanns, 9 Agent Sans (compatible system-sans fallback).",
  );
const textAlign = z.enum(["left", "center", "right"]);
const verticalAlign = z.enum(["top", "middle", "bottom"]);
const styleShape = {
  strokeColor: z
    .string()
    .min(1)
    .max(100)
    .optional()
    .describe("Stroke/text CSS color, for example #1e1e1e."),
  backgroundColor: z
    .string()
    .min(1)
    .max(100)
    .optional()
    .describe(
      "Shape fill CSS color, or transparent. Set fillStyle to solid for a flat fill.",
    ),
  fillStyle: z.enum(["hachure", "cross-hatch", "solid", "zigzag"]).optional(),
  strokeWidth: z.number().nonnegative().max(1000).optional(),
  strokeStyle: z.enum(["solid", "dashed", "dotted"]).optional(),
  roughness: z
    .number()
    .nonnegative()
    .max(10)
    .optional()
    .describe("0 for precise lines; 1 or 2 for hand-drawn variation."),
  opacity: z
    .number()
    .min(0)
    .max(100)
    .optional()
    .describe("Opacity percentage from 0 to 100."),
  roundness: z
    .object({
      type: z.union([z.literal(1), z.literal(2), z.literal(3)]),
      value: z.number().nonnegative().optional(),
    })
    .strict()
    .nullable()
    .optional()
    .describe(
      "null for sharp corners; {type:3} for adaptive rounded corners. Types 1/2 are legacy shapes.",
    ),
  fontFamily: fontFamily.optional(),
  fontSize: z
    .number()
    .positive()
    .max(1000)
    .optional()
    .describe(
      "Text font size in scene units. For a new bound label, use label.fontSize.",
    ),
  textAlign: textAlign.optional(),
  verticalAlign: verticalAlign.optional(),
  angle: coordinate.optional().describe("Rotation in radians."),
  locked: z.boolean().optional(),
  link: z
    .string()
    .max(4096)
    .nullable()
    .optional()
    .describe("Element link, or null to clear it."),
};
const geometryShape = {
  x: coordinate.optional(),
  y: coordinate.optional(),
  width: coordinate.optional(),
  height: coordinate.optional(),
  points: z
    .array(z.tuple([coordinate, coordinate]))
    .min(2)
    .max(10000)
    .optional()
    .describe(
      "Line/arrow points relative to element x,y. Bound arrows usually use from/to instead.",
    ),
};
const labelShape = z
  .object({
    text: z.string(),
    fontSize: z.number().positive().max(1000).optional(),
    fontFamily: fontFamily.optional(),
    textAlign: textAlign.optional(),
    verticalAlign: verticalAlign.optional(),
  })
  .strict();
const operation = z
  .discriminatedUnion("op", [
    z
      .object({
        op: z.literal("canvas"),
        viewBackgroundColor: z.string().max(100),
      })
      .strict(),
    z
      .object({
        op: z.literal("create"),
        type: z.enum([
          "rectangle",
          "ellipse",
          "diamond",
          "text",
          "arrow",
          "line",
        ]),
        id: z
          .string()
          .min(1)
          .optional()
          .describe(
            "Optional explicit stable ID; otherwise generated by the app.",
          ),
        ref: z
          .string()
          .min(1)
          .optional()
          .describe(
            "Unique batch-local name; later arrows can use it for from/to.",
          ),
        ...styleShape,
        ...geometryShape,
        text: z.string().optional().describe("Required when type is text."),
        label: z
          .union([z.string(), labelShape])
          .optional()
          .describe("Bound label text or text plus font/alignment settings."),
        from: z
          .string()
          .optional()
          .describe("Stable element ID or prior create ref for arrow start."),
        to: z
          .string()
          .optional()
          .describe("Stable element ID or prior create ref for arrow end."),
      })
      .strict(),
    z
      .object({
        op: z.literal("update"),
        id: z.string().min(1),
        ...styleShape,
        ...geometryShape,
        text: z
          .string()
          .optional()
          .describe(
            "Replace text on a text element; the app recomputes its metrics.",
          ),
        label: z
          .union([z.string(), labelShape])
          .optional()
          .describe(
            "Replace bound-label text and optional font/alignment settings.",
          ),
      })
      .strict(),
    z.object({ op: z.literal("delete"), id: z.string().min(1) }).strict(),
    z
      .object({
        op: z.literal("group"),
        ids: z.array(z.string().min(1)).min(2),
      })
      .strict(),
  ])
  .superRefine((value, context) => {
    if (
      value.op === "create" &&
      value.type === "text" &&
      value.text === undefined
    )
      context.addIssue({
        code: "custom",
        path: ["text"],
        message: "Text creation requires a text string.",
      });
    if (
      value.op === "create" &&
      value.label !== undefined &&
      !["rectangle", "ellipse", "diamond", "arrow"].includes(value.type)
    )
      context.addIssue({
        code: "custom",
        path: ["label"],
        message:
          "Bound labels are supported on rectangle, ellipse, diamond and arrow. For a text element, use text.",
      });
  });
export function shapeFor(name: string): Record<string, z.ZodTypeAny> {
  const shape: Record<string, z.ZodTypeAny> = { ...commonShape };
  if (
    [
      "save",
      "save-as",
      "move",
      "duplicate",
      "view",
      "render",
      "export",
      "reveal",
    ].includes(name)
  ) {
    shape.document = z.string();
    shape.epoch = z.string();
  }
  if (["apply", "layout", "revert-last-agent-batch"].includes(name)) {
    shape.document = z.string();
    shape.epoch = z.string();
    shape.expectedRevision = z.number().int().nonnegative();
    shape.requestId = z.string().min(1);
  }
  if (name === "apply")
    shape.operations = z
      .array(operation)
      .max(1000)
      .describe(
        "One validated visible batch; create refs can be used by later arrow from/to",
      );
  if (["new", "duplicate", "path-suggest"].includes(name)) {
    shape.title = z
      .string()
      .optional()
      .describe(
        "Suggested filename when path is omitted. An explicit path determines the displayed filename.",
      );
    shape.projectDir = z.string().optional();
  }
  if (["new", "duplicate", "open", "move", "save-as"].includes(name))
    shape.path =
      name === "open" || name === "move" || name === "save-as"
        ? z.string()
        : z.string().optional();
  if (name === "open")
    shape.show = z.boolean().optional().describe("Show and focus the desktop window");
  if (["render", "export"].includes(name)) {
    shape.output = z
      .string()
      .describe("Absolute output path, returned as an artifact");
    shape.format = z.enum(["png", "svg", "excalidraw"]).optional();
    shape.background = z
      .boolean()
      .optional()
      .describe(
        "Include the drawing background. False creates a transparent export.",
      );
    shape.embedScene = z
      .boolean()
      .optional()
      .describe(
        "Include the original editable scene in an image export. Off unless explicitly requested; recipients can reopen its original content.",
      );
    shape.scale = z
      .number()
      .min(0.1)
      .max(4)
      .optional()
      .describe("PNG render scale from 0.1 to 4.");
    shape.selection = z
      .boolean()
      .optional()
      .describe("Export selected shapes and their bound labels only.");
    shape.ids = z
      .array(z.string())
      .optional()
      .describe("Export these stable IDs and their bound labels only.");
  }
  if (name === "list") {
    shape.query = z
      .string()
      .optional()
      .describe("Filter known drawing titles and paths before pagination.");
    shape.offset = z.number().int().nonnegative().optional();
    shape.limit = z
      .number()
      .int()
      .positive()
      .max(500)
      .optional()
      .describe(
        "Page size, default50. Follow nextOffset until null for complete results.",
      );
  }
  if (name === "snapshot") {
    shape.selection = z
      .boolean()
      .optional()
      .describe("Inspect the current selection and its bound labels.");
    shape.group = z
      .string()
      .optional()
      .describe("Inspect shapes belonging to this stable group ID.");
    shape.region = z
      .object({
        x: coordinate,
        y: coordinate,
        width: coordinate,
        height: coordinate,
      })
      .strict()
      .optional()
      .describe("Inspect shapes overlapping this scene rectangle.");
    shape.compact = z.boolean().optional();
    shape.ids = z.array(z.string()).optional();
    shape.offset = z.number().int().nonnegative().optional();
    shape.limit = z.number().int().positive().max(5000).optional();
  }
  if (name === "layout") {
    shape.ids = z.array(z.string()).optional();
    shape.direction = z.enum(["horizontal", "vertical"]).optional();
    shape.gap = z.number().nonnegative().optional();
    shape.x = coordinate.optional();
    shape.y = coordinate.optional();
  }
  if (name === "view") {
    shape.ids = z.array(z.string()).optional();
    shape.zoom = z.number().positive().optional();
    shape.scrollX = z.number().optional();
    shape.scrollY = z.number().optional();
    shape.focus = z.boolean().optional();
  }
  return shape;
}
export function validateRequest(
  name: string,
  input: Record<string, unknown>,
): Request {
  if (!commands.some((c) => c.name === name))
    throw new AppError("UNKNOWN_COMMAND", `Unknown command: ${name}`);
  const checked = z.object(shapeFor(name)).strict().safeParse(input);
  if (!checked.success)
    throw new AppError(
      "INVALID_INPUT",
      checked.error.issues
        .map(
          (i) =>
            `${i.path.join(".") || "input"}: ${i.message}${i.code === "unrecognized_keys" && i.keys.includes("style") ? ". Put style fields such as strokeColor, backgroundColor and fillStyle directly on the operation; a nested style object is not supported." : ""}`,
        )
        .join("; "),
    );
  const parsed = checked.data as Record<string, any>;
  const { document, epoch, expectedRevision, requestId, session, ...args } =
    parsed;
  return {
    command: name,
    args,
    ...(document ? { document } : {}),
    ...(epoch ? { epoch } : {}),
    ...(expectedRevision !== undefined ? { expectedRevision } : {}),
    ...(requestId ? { requestId } : {}),
    ...(session ? { session } : {}),
  };
}
export function schemaDocument() {
  return {
    name: "agent-excalidraw",
    protocol: 1,
    commands: commands.map((command) => ({
      ...command,
      inputSchema: z.toJSONSchema(z.object(shapeFor(command.name)).strict()),
    })),
    mutationPreconditions: [
      "document",
      "epoch",
      "expectedRevision",
      "requestId",
    ],
    input:
      "JSON object through --input <file> or --input -; apply accepts an operation array too",
  };
}
